# Audit entries are append-only. Allowed exceptions: clearing actor_id when the
# acting user's account is deleted (POPIA), and deletes by the retention purge,
# which sets the transaction-local flag ocmp.allow_audit_purge.
GUARD_FUNCTION = """
CREATE OR REPLACE FUNCTION ocmp_audit_log_guard() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF current_setting('ocmp.allow_audit_purge', true) = 'on' THEN
            RETURN OLD;
        END IF;
        RAISE EXCEPTION 'audit log entries cannot be deleted'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF NEW.actor_id IS NULL AND OLD.actor_id IS NOT NULL
       AND (to_jsonb(NEW) - 'actor_id') = (to_jsonb(OLD) - 'actor_id') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'audit log entries cannot be changed'
        USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql
"""

